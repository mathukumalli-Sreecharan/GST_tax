const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {PGlite}=require('@electric-sql/pglite');

test('email actions: additive migration, escaped HTML, frozen retries, owner lookup and audited conflict protection',async()=>{
 const db=new PGlite();
 const owner='11111111-1111-4111-8111-111111111111';
 const applicant='22222222-2222-4222-8222-222222222222';
 const rejected='33333333-3333-4333-8333-333333333333';
 const q=async(sql,p=[])=>(await db.query(sql,p)).rows;
 const claim=async()=>(await q("select public.claim_approval_notification('owner@gmail.com','GST Ledger Studio <onboarding@resend.dev>','https://gst.example.com/admin/approvals') item"))[0].item;
 try{
  await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;
   create schema auth;create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz,raw_user_meta_data jsonb default '{}',created_at timestamptz default now());
   create function auth.uid() returns uuid language sql as $$select null::uuid$$;`);
  for(const name of ['001_profiles.sql','002_user_approvals.sql','004_notification_registration_time.sql','005_admin_request_notifications.sql'])await db.exec(fs.readFileSync('../supabase/migrations/'+name,'utf8'));
  await q("insert into auth.users(id,email,email_confirmed_at) values($1,'owner@gmail.com',now())",[owner]);
  await q('select public.initialize_approval_owner($1)',[owner]);
  const old=await claim();
  await q("select public.finish_approval_notification($1,$2,null,'ambiguous timeout')",[old.id,old.lease_token]);
  const before=await q('select * from public.approval_notifications');
  await db.exec(fs.readFileSync('../supabase/migrations/006_email_approval_actions.sql','utf8'));
  assert.deepEqual(await q('select * from public.approval_notifications'),before);
  await q("insert into auth.users(id,email,email_confirmed_at,raw_user_meta_data) values($1,'applicant@example.com',now(),$2)",[applicant,JSON.stringify({full_name:'<script>alert("x")</script> & <img src=x onerror="alert(1)"> O\'Neil'})]);
  await db.exec('set role service_role');
  const item=await claim();
  assert.deepEqual(item.payload.to,['owner@gmail.com']);
  assert.ok(item.payload.text.includes(`/approval-action?user=${applicant}&decision=approved`));
  assert.ok(item.payload.text.includes(`&decision=rejected`));
  assert.ok(item.payload.html.includes('&lt;script&gt;'));
  assert.ok(!item.payload.html.includes('<script>'));
  assert.ok(!item.payload.html.includes('<img'));
  assert.ok(item.payload.html.includes('&quot;'));
  assert.ok(item.payload.html.includes('&#39;'));
  assert.ok(item.payload.html.includes('&amp;decision=approved'));
  assert.ok(!/token=|secret=/.test(item.payload.html));
  assert.equal(await claim(),null);
  await q("select public.finish_approval_notification($1,$2,null,'temporary failure')",[item.id,item.lease_token]);
  await db.exec('reset role');
  await q("update public.approval_notifications set next_attempt_at=now()-interval '1 minute' where id=$1",[item.id]);
  await db.exec('set role service_role');
  const retry=await claim(); assert.deepEqual(retry.payload,item.payload);assert.equal(retry.id,item.id);
  const lookup=async(actor,user=applicant)=>(await q('select public.admin_approval_applicant($1,$2,$3) item',[actor,owner,user]))[0].item;
  assert.equal((await lookup(owner)).status,'pending');
  await assert.rejects(lookup(applicant),/Owner access required/);
  await assert.rejects(q('select public.admin_approval_applicant($1,null,$2)',[owner,applicant]),/Owner access required/);
  await q("select public.change_approval($1,$1,$2,'approved','pending')",[owner,applicant]);
  assert.equal((await lookup(owner)).status,'approved');
  await assert.rejects(q("select public.change_approval($1,$1,$2,'approved','pending')",[owner,applicant]),/refresh and try again/);
  await assert.rejects(q("select public.change_approval($1,$1,$2,'rejected','pending')",[owner,applicant]),/refresh and try again/);
  await db.exec('reset role');
  await q("insert into auth.users(id,email,email_confirmed_at) values($1,'rejected@example.com',now())",[rejected]);
  await db.exec('set role service_role');
  await q("select public.change_approval($1,$1,$2,'rejected','pending')",[owner,rejected]);
  assert.equal((await lookup(owner,rejected)).status,'rejected');
  await db.exec('reset role');
  assert.equal((await q('select count(*)::int n from public.approval_audit'))[0].n,3);
  await db.exec('set role authenticated');
  await assert.rejects(lookup(owner),/permission denied/);
  await db.exec('reset role;set role anon');
  await assert.rejects(lookup(owner),/permission denied/);
 }finally{await db.close();}
});
